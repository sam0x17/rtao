//! Portable receipt tables from the authenticated Rust-only named-table corpus.

use anyhow::{Context, Result, ensure};
use serde_json::Value;
use sha2::{Digest, Sha256};
use std::{
    collections::BTreeSet,
    fs,
    io::Write,
    path::Path,
    process::{Command, Stdio},
};
use toml_edit::DocumentMut;

const RECEIPT: &str = "sdk/python/bittensor/_transport/utils/receipt.py";
const ERRORS: &str = "sdk/python/bittensor/error_map.py";
const OUTPUT: &str = "crates/rtao-core-ext/src/ops/receipt_tables.rs";
const DISPATCH_OUTPUT: &str = "crates/rtao-core-ext/src/ops/dispatch_error_tables.rs";

fn format_source(source: &str) -> Result<String> {
    let mut child = Command::new("rustfmt")
        .args(["--edition", "2024", "--emit", "stdout"])
        .stdin(Stdio::piped())
        .stdout(Stdio::piped())
        .stderr(Stdio::piped())
        .spawn()?;
    child
        .stdin
        .take()
        .context("rustfmt stdin missing")?
        .write_all(source.as_bytes())?;
    let output = child.wait_with_output()?;
    ensure!(
        output.status.success(),
        "rustfmt rejected receipt tables: {}",
        String::from_utf8_lossy(&output.stderr)
    );
    Ok(String::from_utf8(output.stdout)?)
}

fn string(value: &Value) -> Result<&str> {
    value
        .as_str()
        .context("receipt table value is not a string")
}

fn authenticated<'a>(
    root: &Path,
    pins: &DocumentMut,
    tables: &'a Value,
    path: &str,
) -> Result<(&'a Value, String)> {
    let source = fs::read(root.join("vendor/upstream/src").join(path))?;
    let sha = hex::encode(Sha256::digest(&source));
    ensure!(
        pins["artifacts"][path]["sha256"].as_str() == Some(sha.as_str()),
        "receipt extraction source SHA256 differs from pin: {path}"
    );
    let module = &tables["tables"][path];
    ensure!(
        module["provenance"]["commit"].as_str() == pins["parity"]["commit"].as_str(),
        "receipt table commit differs from pin"
    );
    ensure!(
        module["provenance"]["path"].as_str() == Some(path),
        "receipt table path differs from source"
    );
    Ok((module, sha))
}

pub(crate) fn extract_at(root: &Path, check: bool) -> Result<()> {
    // The caller runs resolved::extract_at first, authenticating the complete
    // corpus against its Python AST inputs before this rendering step.
    let pins = fs::read_to_string(root.join("upstream.toml"))?.parse::<DocumentMut>()?;
    let tables: Value = serde_json::from_slice(&fs::read(
        root.join("vendor/upstream/extracted/named_tables.json"),
    )?)?;
    let (receipt, receipt_sha) = authenticated(root, &pins, &tables, RECEIPT)?;
    let (errors, errors_sha) = authenticated(root, &pins, &tables, ERRORS)?;
    let header = format!(
        "// @generated by cargo xtask extract; do not edit.\n// Python receipt source SHA256 {receipt_sha}.\n// Python error-map source SHA256 {errors_sha}.\n// Upstream commit {}.\n\n",
        pins["parity"]["commit"]
            .as_str()
            .context("parity commit missing")?
    );
    let mut output = header.clone();
    output.push_str("/// Python's ordered nested dispatch-result event fields.\npub(super) const NESTED_RESULT_EVENTS: &[(&str, &str, &str)] = &[\n");
    let entries = receipt["values"]["_NESTED_RESULT_EVENTS"]["value"]["dict"]
        .as_array()
        .context("nested receipt table missing; run resolved extraction first")?;
    ensure!(!entries.is_empty(), "nested receipt table is empty");
    let mut seen = BTreeSet::new();
    for entry in entries {
        let tuple = entry[0]["tuple"]
            .as_array()
            .context("nested event key is not a tuple")?;
        ensure!(tuple.len() == 2, "nested event key tuple differs");
        let module = string(&tuple[0])?;
        let event = string(&tuple[1])?;
        let field = string(&entry[1])?;
        ensure!(seen.insert((module, event)), "duplicate nested event key");
        output.push_str(&format!("    ({module:?}, {event:?}, {field:?}),\n"));
    }
    output.push_str("];\n");
    let receipt_output = format_source(&output)?;
    let mut output = header;
    output.push_str("/// Exact Python system-dispatch descriptions.\npub(super) const DISPATCH_ERROR_DOCS: &[(&str, &str)] = &[\n");
    let entries = errors["values"]["DISPATCH_ERRORS"]["value"]["dict"]
        .as_array()
        .context("dispatch error table is missing")?;
    let mut seen = BTreeSet::new();
    for entry in entries {
        let name = string(&entry[0])?;
        let tuple = entry[1]["tuple"]
            .as_array()
            .context("dispatch error row is not a tuple")?;
        ensure!(tuple.len() == 2, "dispatch error row tuple differs");
        let docs = string(&tuple[1])?;
        ensure!(seen.insert(name), "duplicate dispatch error name");
        output.push_str(&format!("    ({name:?}, {docs:?}),\n"));
    }
    output.push_str("];\n");
    let output = format_source(&output)?;
    for (relative, output) in [(OUTPUT, receipt_output), (DISPATCH_OUTPUT, output)] {
        let path = root.join(relative);
        if check {
            ensure!(
                fs::read_to_string(path)? == output,
                "portable table {relative} is stale; run cargo xtask extract"
            );
        } else if fs::read_to_string(&path).ok().as_deref() != Some(output.as_str()) {
            fs::write(path, output)?;
        }
    }
    Ok(())
}

