    #[test]
    fn every_operation_has_a_page_and_catalog_extension_preserves_upstream_records() -> Result<()> {
        let root = Path::new(env!("CARGO_MANIFEST_DIR"))
            .parent()
            .context("workspace root")?;
        // This fixture can audit a partially ported checkout too; the command
        // separately rejects a stale pending register before writing outputs.
        let pending_reads = ast(root, READ_SOURCE)?
            .items
            .iter()
            .filter_map(|item| match item {
                syn::Item::Fn(item)
                    if item
                        .block
                        .to_token_stream()
                        .to_string()
                        .contains("NotYetPorted") =>
                {
                    Some(item.sig.ident.to_string())
                }
                _ => None,
            })
            .collect();
        let generated = pages(root, &BTreeSet::new(), &pending_reads)?;
        assert_eq!(generated.len(), INTENTS.len() + READS.len() + 3);
        for (directory, specs) in [
            (
                "tx",
                INTENTS
                    .iter()
                    .map(|spec| (spec.name, spec.description, spec.catalog_json))
                    .collect::<Vec<_>>(),
            ),
            (
                "query",
                READS
                    .iter()
                    .map(|spec| (spec.name, spec.description, spec.catalog_json))
                    .collect(),
            ),
        ] {
            let file = if directory == "tx" {
                "intents"
            } else {
                "reads"
            };
            let catalog: Vec<Value> =
                serde_json::from_str(&generated[&format!("catalog/{file}.json")])?;
            assert_eq!(catalog.len(), specs.len());
            for ((name, prose, original), mut row) in specs.into_iter().zip(catalog) {
                let page = &generated[&format!("{directory}/{name}.md")];
                assert!(page.contains(prose), "description missing from {name}");
                assert!(page.contains("\n## Rust\n"));
                assert!(!page.contains("#L"));
                let metadata = row
                    .as_object_mut()
                    .context("catalog record")?
                    .remove("rust")
                    .context("Rust metadata")?;
                assert!(metadata["output"].is_string());
                assert_eq!(row, serde_json::from_str::<Value>(original)?);
            }
        }
        let original: Value = serde_json::from_str(&fs::read_to_string(
            root.join("vendor/upstream/catalog/errors.json"),
        )?)?;
        let mut extended: Value = serde_json::from_str(&generated["catalog/errors.json"])?;
        for group in ["codes", "chain_errors"] {
            for entry in extended[group]
                .as_object_mut()
                .context("error group")?
                .values_mut()
            {
                assert!(
                    entry
                        .as_object_mut()
                        .context("error entry")?
                        .remove("rust")
                        .is_some()
                );
            }
        }
        assert_eq!(extended, original);
        Ok(())
    }
