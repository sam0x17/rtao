//! Catalog pages use authenticated prose and the actual generated Rust AST.

use std::{
    collections::{BTreeMap, BTreeSet},
    fs,
    path::{Component, Path},
};

use anyhow::{Context, Result, ensure};
use quote::ToTokens;
use rtao_catalog::{INTENTS, READS};
use serde_json::{Value, json};

use super::{code, constructor_fields, default_text, schema_block, table_text};

const INTENT_SOURCE: &str = "crates/rtao-intents/src/generated/interfaces.rs";
const READ_SOURCE: &str = "crates/rtao-reads/src/generated/interfaces.rs";
const GENERATED: &str = "<!-- Generated by cargo xtask docs; do not edit. -->\n\n";

fn ast(root: &Path, path: &str) -> Result<syn::File> {
    syn::parse_file(&fs::read_to_string(root.join(path))?)
        .with_context(|| format!("parse documentation interface {path}"))
}

fn public_type(ty: &syn::Type, crate_name: &str) -> String {
    ty.to_token_stream()
        .to_string()
        .replace("crate ::", &format!("{crate_name} ::"))
}

fn fields(item: &syn::ItemStruct, crate_name: &str) -> Result<BTreeMap<String, String>> {
    item.fields
        .iter()
        .map(|field| {
            Ok((
                field
                    .ident
                    .as_ref()
                    .context("named interface field")?
                    .to_string(),
                public_type(&field.ty, crate_name),
            ))
        })
        .collect()
}

fn identifier(value: &str) -> Result<()> {
    ensure!(
        !value.is_empty()
            && value
                .bytes()
                .all(|byte| byte.is_ascii_alphanumeric() || byte == b'_'),
        "invalid reference identifier {value:?}"
    );
    Ok(())
}

fn upstream_url(path: &str) -> Result<String> {
    ensure!(
        path.starts_with('/') && !path.starts_with("//") && !path.contains(['\n', '\r', '#']),
        "invalid authenticated upstream path"
    );
    Ok(format!("https://www.bittensor.com{path}"))
}

fn upstream_links(catalog: &Value) -> Result<String> {
    Ok(format!(
        "[Upstream page]({}) · [Upstream raw Markdown]({})\n\n",
        upstream_url(catalog["docs_url"].as_str().context("catalog docs_url")?)?,
        upstream_url(
            catalog["markdown_url"]
                .as_str()
                .context("catalog markdown_url")?
        )?
    ))
}

fn source_link(path: &str, item: &str) -> Result<String> {
    ensure!(
        !path.is_empty()
            && !path.starts_with('/')
            && !path.split('/').any(|part| part == "..")
            && !path.contains(['#', '\n', '\r', ')']),
        "invalid source citation path"
    );
    Ok(format!(
        "- {} — {} ([source](https://www.bittensor.com/code/raw/{path}))\n",
        code(path),
        code(item)
    ))
}

fn sources(catalog: &Value, kind: &str) -> Result<String> {
    let mut text = String::new();
    let Some(rows) = catalog.get(kind).and_then(Value::as_array) else {
        return Ok(text);
    };
    for row in rows {
        let item = if kind == "hits" {
            format!(
                "{}.{} ({})",
                row["container"].as_str().context("read source container")?,
                row["name"].as_str().context("read source item")?,
                row["kind"].as_str().context("read source kind")?
            )
        } else {
            format!(
                "{}.{}",
                row["pallet"].as_str().context("call source pallet")?,
                row["call"].as_str().context("call source item")?
            )
        };
        if let Some(path) = row["path"].as_str() {
            text.push_str(&source_link(path, &item)?);
        } else {
            ensure!(kind == "hits", "transaction source has no declaration path");
            // FRAME and selectively decoded storage hits can intentionally
            // lack a vendored declaration. Cite the descriptor's real record
            // rather than guessing a pallet file.
            text.push_str(&source_link(
                "website/apps/bittensor-website/public/catalog/reads.json",
                &item,
            )?);
            text.push_str(
                "  The pinned catalog supplies no declaration path for this descriptor.\n",
            );
        }
    }
    Ok(text)
}

fn source_status(pending: bool) -> &'static str {
    if pending {
        "pending behavior port; the interface refuses execution"
    } else {
        "implemented source; hosted acceptance is recorded separately"
    }
}

fn error_catalog(root: &Path) -> Result<String> {
    let mut catalog: Value = serde_json::from_str(&fs::read_to_string(
        root.join("vendor/upstream/catalog/errors.json"),
    )?)?;
    for (group, items) in [
        (
            "codes",
            rtao_catalog::SEMANTIC_ERRORS
                .iter()
                .map(|spec| (spec.code.as_str(), "rtao_catalog::ErrorCode"))
                .collect::<Vec<_>>(),
        ),
        (
            "chain_errors",
            rtao_catalog::CHAIN_ERRORS
                .iter()
                .map(|spec| (spec.name, "rtao_tx::ChainError"))
                .collect(),
        ),
    ] {
        let rows = catalog[group]
            .as_object_mut()
            .context("error catalog group")?;
        ensure!(
            rows.len() == items.len(),
            "error catalog membership differs"
        );
        for (name, ty) in items {
            let entry = rows.get_mut(name).context("catalog error entry")?;
            let source = if group == "chain_errors" {
                "crates/rtao-tx/src/error.rs"
            } else {
                "crates/rtao-catalog/src/errors.rs"
            };
            entry["rust"] = json!({"type":ty,"source":source,"catalog_source":"crates/rtao-catalog/src/errors.rs","classification":"rtao_tx::ChainError::code"});
        }
    }
    Ok(format!("{}\n", serde_json::to_string_pretty(&catalog)?))
}

fn rust_table(values: &[(&str, String)]) -> String {
    let mut text = "| Rust contract | Value |\n|---|---|\n".to_owned();
    for (name, value) in values {
        text.push_str(&format!("| {name} | {} |\n", code(value)));
    }
    text.push('\n');
    text
}

fn input_table(typed: &BTreeMap<String, String>) -> String {
    if typed.is_empty() {
        return "No input fields.\n\n".into();
    }
    let mut text = "| Input field | Rust type |\n|---|---|\n".to_owned();
    for (name, ty) in typed {
        text.push_str(&format!("| {} | {} |\n", code(name), code(ty)));
    }
    text.push('\n');
    text
}

fn feature_gate(item: &syn::ItemStruct) -> Result<String> {
    let gates = item
        .attrs
        .iter()
        .filter(|attribute| attribute.path().is_ident("cfg"))
        .map(|attribute| -> Result<String> {
            let syn::Meta::NameValue(gate) = attribute.parse_args::<syn::Meta>()? else {
                anyhow::bail!("intent feature gate must name one feature")
            };
            ensure!(gate.path.is_ident("feature"), "unexpected intent gate");
            let syn::Expr::Lit(literal) = gate.value else {
                anyhow::bail!("nonliteral intent feature")
            };
            let syn::Lit::Str(feature) = literal.lit else {
                anyhow::bail!("non-string intent feature")
            };
            Ok(feature.value())
        })
        .collect::<Result<Vec<_>>>()?;
    ensure!(gates.len() == 1, "intent must have one Cargo feature gate");
    Ok(gates[0].clone())
}

fn result_type(function: &syn::ItemFn) -> Result<&syn::Type> {
    let syn::ReturnType::Type(_, ty) = &function.sig.output else {
        anyhow::bail!("read has no result type")
    };
    let syn::Type::Path(path) = ty.as_ref() else {
        anyhow::bail!("read result is not a path")
    };
    let result = path.path.segments.last().context("read result path")?;
    ensure!(result.ident == "Result", "read result is not Result");
    let syn::PathArguments::AngleBracketed(args) = &result.arguments else {
        anyhow::bail!("read result has no arguments")
    };
    let Some(syn::GenericArgument::Type(output)) = args.args.first() else {
        anyhow::bail!("read result has no output type")
    };
    Ok(output)
}

pub(super) fn pages(
    root: &Path,
    pending: &BTreeSet<String>,
    pending_reads: &BTreeSet<String>,
) -> Result<BTreeMap<String, String>> {
    let intents = ast(root, INTENT_SOURCE)?;
    let reads = ast(root, READ_SOURCE)?;
    let mut outputs = BTreeMap::new();
    let mut tx_catalog = Vec::new();
    let mut read_catalog = Vec::new();
    for spec in &INTENTS {
        identifier(spec.name)?;
        let mut catalog: Value = serde_json::from_str(spec.catalog_json)?;
        let schema = catalog.get("input_schema").context("intent schema")?;
        let structure = intents
            .items
            .iter()
            .find_map(|item| match item {
                syn::Item::Struct(item) if item.ident == spec.python_class => Some(item),
                _ => None,
            })
            .with_context(|| format!("missing Rust intent {}", spec.name))?;
        let implementation = intents
            .items
            .iter()
            .find_map(|item| match item {
                syn::Item::Impl(item)
                    if item.self_ty.to_token_stream().to_string() == spec.python_class
                        && item.trait_.as_ref().is_some_and(|(_, path, _)| {
                            path.segments
                                .last()
                                .is_some_and(|part| part.ident == "IntentInterface")
                        }) =>
                {
                    Some(item)
                }
                _ => None,
            })
            .context("intent interface implementation")?;
        let associated = |name: &str| -> Result<String> {
            implementation
                .items
                .iter()
                .find_map(|item| match item {
                    syn::ImplItem::Type(item) if item.ident == name => {
                        Some(public_type(&item.ty, "rtao_intents"))
                    }
                    _ => None,
                })
                .with_context(|| format!("missing associated {name} for {}", spec.name))
        };
        let vars: Value = serde_json::from_str(spec.class_vars_json)?;
        let python_path = vars["op"]["provenance"]["path"]
            .as_str()
            .context("intent declaration path")?;
        let feature = feature_gate(structure)?;
        let rust_type = format!("rtao_intents::{}", spec.python_class);
        let role = associated("Role")?;
        let output = associated("Output")?;
        let input_types = fields(structure, "rtao_intents")?;
        ensure!(
            input_types
                .keys()
                .map(String::as_str)
                .collect::<BTreeSet<_>>()
                == spec.fields.iter().map(|field| field.name).collect(),
            "intent input mapping drift for {}",
            spec.name
        );
        let command = (!pending.contains(spec.name))
            .then(|| format!("rtao tx {}", spec.name.replace('_', "-")));
        let mut text = format!(
            "{GENERATED}# {}\n\n{}\n\n{}",
            spec.name,
            spec.description,
            upstream_links(&catalog)?
        );
        text.push_str(&format!("## Contract\n\n| Contract | Value |\n|---|---|\n| Python class | {} |\n| Signing role | {} |\n| Dispatch origin | {} |\n| MEV shield default | {} |\n| MEV shield required | {} |\n| Verification read | {} |\n\n", code(spec.python_class), code(spec.signer), code(spec.origin), spec.mev_shield_default, spec.mev_shield_required, spec.verify.map_or_else(|| "none".into(), code)));
        let calls = spec
            .wraps
            .iter()
            .map(|(pallet, call)| code(&format!("{pallet}.{call}")))
            .collect::<Vec<_>>()
            .join(", ");
        let all = spec
            .all_amount_fields
            .iter()
            .map(|field| code(field))
            .collect::<Vec<_>>()
            .join(", ");
        text.push_str(&format!(
            "**Catalog calls:** {}. **Fields accepting `all`:** {}.\n\n",
            if calls.is_empty() { "none" } else { &calls },
            if all.is_empty() { "none" } else { &all }
        ));
        text.push_str("## Constructor fields\n\n");
        text.push_str(&constructor_fields(spec, schema)?);
        text.push_str("\n## Rust\n\n");
        text.push_str(&format!("**Source status:** {}. Feature availability depends on the consuming build. Checked native `u64` rao amounts are documented in [compatibility](../compat.md).\n\n", source_status(pending.contains(spec.name))));
        text.push_str(&rust_table(&[
            ("Type", rust_type.clone()),
            ("Cargo feature", feature.clone()),
            ("Signing role", role.clone()),
            ("Origin", associated("Origin")?),
            ("Output", output.clone()),
            (
                "CLI",
                command.clone().unwrap_or_else(|| "unavailable".into()),
            ),
        ]));
        text.push_str(&input_table(&input_types));
        text.push_str(&format!(
            "**Rust source:** {} — {} and {}.\n\n## Sources\n\n",
            code(INTENT_SOURCE),
            code(spec.python_class),
            code("IntentInterface")
        ));
        text.push_str(&source_link(python_path, spec.python_class)?);
        text.push_str(&sources(&catalog, "sources")?);
        text.push_str("\n## Input schema\n\n");
        text.push_str(&schema_block(schema)?);
        outputs.insert(format!("tx/{}.md", spec.name), text);
        catalog["rust"] = json!({"type":rust_type,"role":role,"output":output,"feature":feature,"cli":command,"input_types":input_types,"source":INTENT_SOURCE,"implemented":!pending.contains(spec.name),"validation":"source metadata; hosted acceptance recorded separately"});
        tx_catalog.push(catalog);
    }
    for spec in &READS {
        identifier(spec.name)?;
        let mut catalog: Value = serde_json::from_str(spec.catalog_json)?;
        let function = reads
            .items
            .iter()
            .find_map(|item| match item {
                syn::Item::Fn(item) if item.sig.ident == spec.name => Some(item),
                _ => None,
            })
            .with_context(|| format!("missing generated read {}", spec.name))?;
        let structure = reads
            .items
            .iter()
            .filter_map(|item| match item {
                syn::Item::Struct(item) => Some(item),
                _ => None,
            })
            .find(|item| {
                item.ident
                    .to_string()
                    .strip_suffix("Params")
                    .is_some_and(|name| name.to_ascii_lowercase() == spec.name.replace('_', ""))
            })
            .with_context(|| format!("missing generated read parameters {}", spec.name))?;
        let input_types = fields(structure, "rtao_reads")?;
        ensure!(
            input_types
                .keys()
                .map(String::as_str)
                .collect::<BTreeSet<_>>()
                == spec.params.iter().map(|field| field.name).collect(),
            "read input mapping drift for {}",
            spec.name
        );
        let is_stub = function
            .block
            .to_token_stream()
            .to_string()
            .contains("NotYetPorted");
        ensure!(
            is_stub == pending_reads.contains(spec.name),
            "read {} source/pending status disagrees; regenerate interfaces before docs",
            spec.name
        );
        let output = public_type(result_type(function)?, "rtao_reads");
        let method = format!("rtao_reads::generated::interfaces::{}", spec.name);
        let params_type = format!("rtao_reads::generated::interfaces::{}", structure.ident);
        let provenance: Value = serde_json::from_str(spec.provenance_json)?;
        let python_path = provenance["declaration"]["path"]
            .as_str()
            .context("read declaration path")?;
        let python = catalog["python"]
            .as_str()
            .context("catalog Python read expression")?;
        let command = (!is_stub).then(|| format!("rtao query {}", spec.name.replace('_', "-")));
        let mut text = format!(
            "{GENERATED}# {}\n\n{}\n\n{}## Parameters\n\n",
            spec.name,
            spec.description,
            upstream_links(&catalog)?
        );
        if spec.params.is_empty() {
            text.push_str("No parameters.\n\n");
        } else {
            text.push_str("| Parameter | Python type | Required | Default (JSON) | Own-key fallback | Description |\n|---|---|---|---|---|---|\n");
            for field in spec.params {
                text.push_str(&format!(
                    "| {} | {} | {} | {} | {} | {} |\n",
                    code(field.name),
                    code(field.annotation.unwrap_or("undeclared")),
                    if field.required { "yes" } else { "no" },
                    default_text(field)?,
                    field.own_key,
                    table_text(catalog["param_docs"][field.name].as_str().unwrap_or(""))
                ));
            }
            text.push('\n');
        }
        text.push_str(&format!("## Rust\n\n**Source status:** {}. This method borrows a `View`; a snapshot pins its reads to one block. Hosted acceptance is recorded separately.\n\n", source_status(is_stub)));
        text.push_str(&rust_table(&[
            ("Read method", method.clone()),
            ("Parameters", params_type.clone()),
            ("Output", output.clone()),
            ("Python expression", python.into()),
            (
                "CLI",
                command.clone().unwrap_or_else(|| "unavailable".into()),
            ),
        ]));
        text.push_str(&input_table(&input_types));
        text.push_str(&format!(
            "**Rust source:** {} — {}.\n\n## Sources\n\n",
            code(READ_SOURCE),
            code(spec.name)
        ));
        text.push_str(&source_link(python_path, spec.name)?);
        text.push_str(&sources(&catalog, "hits")?);
        outputs.insert(format!("query/{}.md", spec.name), text);
        catalog["rust"] = json!({"method":method,"params_type":params_type,"output":output,"cli":command,"input_types":input_types,"source":READ_SOURCE,"implemented":!is_stub,"validation":"source metadata; hosted acceptance recorded separately"});
        read_catalog.push(catalog);
    }
    outputs.insert(
        "catalog/intents.json".into(),
        format!("{}\n", serde_json::to_string_pretty(&tx_catalog)?),
    );
    outputs.insert(
        "catalog/reads.json".into(),
        format!("{}\n", serde_json::to_string_pretty(&read_catalog)?),
    );
    outputs.insert("catalog/errors.json".into(), error_catalog(root)?);
    Ok(outputs)
}

pub(super) fn add_indexes(root: &Path, pages: &mut BTreeMap<String, String>) -> Result<()> {
    let groups = [
        ("tx", "Transactions"),
        ("query", "Queries"),
        ("errors", "Semantic errors"),
        ("errors/chain", "Chain errors"),
        ("hyperparameters", "Hyperparameters"),
    ];
    let mut reference = format!(
        "{GENERATED}# Reference\n\nThese pages preserve authenticated upstream descriptions and record Rust mappings from this checkout. Source implementation and feature metadata do not establish successful hosted acceptance or live-chain coverage.\n\n"
    );
    let mut summary = String::from("  - [Compatibility](compat.md)\n");
    for (directory, title) in groups {
        let entries: Vec<_> = pages
            .keys()
            .filter(|name| {
                Path::new(name).parent() == Some(Path::new(directory)) && name.ends_with(".md")
            })
            .cloned()
            .collect();
        let mut index = format!("{GENERATED}# {title}\n\n");
        reference.push_str(&format!(
            "- [{title}]({directory}/index.md) — {} entries\n",
            entries.len()
        ));
        summary.push_str(&format!("  - [{title}]({directory}/index.md)\n"));
        for path in entries {
            let name = Path::new(&path)
                .file_stem()
                .and_then(|name| name.to_str())
                .context("reference page stem")?;
            index.push_str(&format!("- [{name}]({name}.md)\n"));
            summary.push_str(&format!("    - [{name}]({path})\n"));
        }
        pages.insert(format!("{directory}/index.md"), index);
    }
    reference.push_str("\n- [Python and Rust API index](api-index.md)\n- [Combined transaction reference](tx-reference.md)\n- [Intent catalog](catalog/intents.json)\n- [Read catalog](catalog/reads.json)\n- [Error catalog](catalog/errors.json)\n");
    pages.insert("reference.md".into(), reference);
    let source = fs::read_to_string(root.join("book/src/SUMMARY.md"))?;
    ensure!(
        source
            .matches("- [Generated reference](reference.md)")
            .count()
            == 1,
        "book summary must have exactly one generated reference placeholder"
    );
    pages.insert(
        "SUMMARY.md".into(),
        source.replace(
            "- [Generated reference](reference.md)\n",
            &format!("- [Generated reference](reference.md)\n{summary}"),
        ),
    );
    Ok(())
}

pub(super) fn llms_index(pages: &BTreeMap<String, String>) -> Result<String> {
    let mut text = "# rtao\n\n> Rust SDK for Bittensor. Source mappings describe this checkout; validation evidence is recorded separately.\n\nThe downloadable book includes Rust API documentation in `api/`. Read `llms-full.txt` for the complete generated reference and source signatures.\n\n## Book\n\n- [Getting started](getting-started.md)\n- [Reference](reference.md)\n- [Compatibility](compat.md)\n- [Python and Rust API index](api-index.md)\n\n## Catalogs\n\n- [Intent catalog](catalog/intents.json)\n- [Read catalog](catalog/reads.json)\n- [Error catalog](catalog/errors.json)\n\n## Upstream mappings\n\n| rtao page | Upstream raw Markdown | Rust entry point |\n|---|---|---|\n".to_owned();
    for file in ["catalog/intents.json", "catalog/reads.json"] {
        let catalog: Value = serde_json::from_str(pages.get(file).context("LLM catalog")?)?;
        let directory = if file.contains("intents") {
            "tx"
        } else {
            "query"
        };
        for entry in catalog.as_array().context("LLM catalog entries")? {
            let name = entry["name"].as_str().context("catalog name")?;
            let path = format!("{directory}/{name}.md");
            ensure!(
                pages.contains_key(&path),
                "LLM mapping has no reference page"
            );
            let rust = entry["rust"][if directory == "tx" { "type" } else { "method" }]
                .as_str()
                .context("Rust catalog mapping")?;
            text.push_str(&format!(
                "| [{name}]({path}) | [raw]({}) | {} |\n",
                upstream_url(
                    entry["markdown_url"]
                        .as_str()
                        .context("upstream Markdown mapping")?
                )?,
                code(rust)
            ));
        }
    }
    Ok(text)
}

fn regular_parent(out: &Path, path: &Path, check: bool) -> Result<()> {
    let mut current = out.to_path_buf();
    let components: Vec<_> = path.components().collect();
    ensure!(
        !components.is_empty()
            && components
                .iter()
                .all(|part| matches!(part, Component::Normal(_))),
        "unsafe generated documentation path"
    );
    for component in components.iter().take(components.len() - 1) {
        current.push(component.as_os_str());
        if !current.exists() && !check {
            fs::create_dir(&current)?;
        }
        let metadata = fs::symlink_metadata(&current)?;
        ensure!(
            metadata.is_dir() && !metadata.file_type().is_symlink(),
            "generated documentation parent must be a regular directory"
        );
    }
    Ok(())
}

fn generated_files(root: &Path, dir: &Path, files: &mut BTreeSet<String>) -> Result<()> {
    if !dir.exists() {
        return Ok(());
    }
    for entry in fs::read_dir(dir)? {
        let path = entry?.path();
        let kind = fs::symlink_metadata(&path)?.file_type();
        ensure!(
            !kind.is_symlink(),
            "generated documentation contains a symlink"
        );
        if kind.is_dir() {
            generated_files(root, &path, files)?;
        } else {
            ensure!(
                kind.is_file(),
                "generated documentation contains a non-file"
            );
            files.insert(
                path.strip_prefix(root)?
                    .to_str()
                    .context("UTF-8 generated docs path")?
                    .to_owned(),
            );
        }
    }
    Ok(())
}

pub(super) fn write_outputs(
    out: &Path,
    mut outputs: BTreeMap<String, String>,
    check: bool,
) -> Result<()> {
    let previous_manifest = out.join("reference-manifest.json");
    match fs::symlink_metadata(&previous_manifest) {
        Ok(metadata) => {
            ensure!(metadata.is_file(), "reference manifest must be regular");
            let previous: Vec<String> = serde_json::from_slice(&fs::read(&previous_manifest)?)?;
            for name in previous {
                let relative = Path::new(&name);
                ensure!(
                    relative
                        .components()
                        .all(|part| matches!(part, Component::Normal(_))),
                    "invalid previous reference path"
                );
                if relative.components().count() == 1 && !outputs.contains_key(&name) {
                    ensure!(
                        fs::symlink_metadata(out.join(&name))
                            .is_err_and(|error| { error.kind() == std::io::ErrorKind::NotFound }),
                        "obsolete generated documentation remains: {name}"
                    );
                }
            }
        }
        Err(error) if error.kind() == std::io::ErrorKind::NotFound => {}
        Err(error) => return Err(error.into()),
    }
    let manifest = format!(
        "{}\n",
        serde_json::to_string_pretty(&outputs.keys().collect::<Vec<_>>())?
    );
    outputs.insert("reference-manifest.json".into(), manifest);
    for (name, bytes) in &outputs {
        let relative = Path::new(name);
        regular_parent(out, relative, check)?;
        let path = out.join(relative);
        if path.symlink_metadata().is_ok() {
            ensure!(
                fs::symlink_metadata(&path)?.file_type().is_file(),
                "docs output must be a regular file"
            );
        }
        if check {
            ensure!(
                fs::read_to_string(&path)? == *bytes,
                "{} is stale",
                path.display()
            );
        } else {
            fs::write(path, bytes)?;
        }
    }
    // Compare owned reference directories as sets as well as bytes. A removed
    // operation must not remain discoverable as an obsolete book page.
    let mut actual = BTreeSet::new();
    for dir in ["tx", "query", "errors", "hyperparameters", "catalog"] {
        generated_files(out, &out.join(dir), &mut actual)?;
    }
    let expected: BTreeSet<_> = outputs
        .keys()
        .filter(|path| path.contains('/'))
        .cloned()
        .collect();
    ensure!(
        actual == expected,
        "generated documentation contains obsolete or missing reference paths"
    );
    Ok(())
}

