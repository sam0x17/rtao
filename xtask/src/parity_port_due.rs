//! Hand ports an automatic runtime adoption left due (`parity/port_due.toml`).
//!
//! A runtime adoption (`parity report --adopt`) moves the parity pin with the
//! runtime Finney finalized. Upstream sources whose change it cannot reconcile
//! on evidence alone (a hand-ported, oracle-only or n/a row whose symbols
//! changed) keep their last reconciled blob in `parity/map.toml` and are
//! listed here with the exact blob they changed to. Ordinary parity accepts a
//! listed change; strict parity names it until a maintainer ports the file and
//! runs `parity bless`, which removes the entry. An entry that no longer
//! describes the map row and the authenticated tree fails both modes.

use std::collections::BTreeMap;
use std::fs;
use std::path::Path;

use anyhow::{Context, Result, ensure};
use toml_edit::{Array, ArrayOfTables, DocumentMut, Item, Table, value};

pub(super) const PATH: &str = "parity/port_due.toml";

const HEADER: &str = "# Generated by cargo xtask parity report --adopt; cargo xtask parity bless removes\n\
# an entry once its file is ported. Each entry keeps the last reconciled blob\n\
# (`from`, equal to the map row's synced_blob) and the upstream blob it changed\n\
# to (`to`), first seen at `tag`. Ordinary parity accepts these exact changes;\n\
# strict parity reports them as due.\n";

#[derive(Debug, Clone, PartialEq, Eq)]
pub(super) struct Entry {
    pub(super) py: String,
    pub(super) kind: String,
    pub(super) from: String,
    pub(super) to: String,
    pub(super) tag: String,
    pub(super) symbols: Vec<String>,
}

pub(super) type PortDue = BTreeMap<String, Entry>;

/// The committed entries; an absent file is an empty set.
pub(super) fn read(root: &Path) -> Result<PortDue> {
    let path = root.join(PATH);
    match fs::symlink_metadata(&path) {
        Ok(metadata) => {
            ensure!(metadata.is_file(), "{PATH} must be a regular file");
            parse(&fs::read_to_string(path)?)
        }
        Err(error) if error.kind() == std::io::ErrorKind::NotFound => Ok(PortDue::new()),
        Err(error) => Err(error.into()),
    }
}

pub(super) fn parse(contents: &str) -> Result<PortDue> {
    let document: DocumentMut = contents.parse().with_context(|| format!("parse {PATH}"))?;
    let mut due = PortDue::new();
    let Some(item) = document.get("file") else {
        return Ok(due);
    };
    for table in item
        .as_array_of_tables()
        .with_context(|| format!("{PATH} rows must be [[file]] tables"))?
    {
        let item = Item::Table(table.clone());
        let field = |key: &str| super::required_string(&item, key).map(str::to_owned);
        let entry = Entry {
            py: field("py")?,
            kind: field("kind")?,
            from: field("from")?,
            to: field("to")?,
            tag: field("tag")?,
            symbols: item
                .get("symbols")
                .and_then(Item::as_array)
                .with_context(|| format!("{PATH}: symbols must be an array"))?
                .iter()
                .map(|name| {
                    name.as_str()
                        .map(str::to_owned)
                        .with_context(|| format!("{PATH}: symbol names must be strings"))
                })
                .collect::<Result<_>>()?,
        };
        ensure!(
            super::valid_path(&entry.py),
            "{PATH}: invalid path {:?}",
            entry.py
        );
        ensure!(
            super::valid_sha(&entry.from) && super::valid_sha(&entry.to) && entry.from != entry.to,
            "{PATH}: {} needs two different git blob SHAs",
            entry.py
        );
        ensure!(
            super::KINDS.contains(&entry.kind.as_str()),
            "{PATH}: {} has invalid kind {:?}",
            entry.py,
            entry.kind
        );
        ensure!(!entry.tag.is_empty(), "{PATH}: {} has no tag", entry.py);
        let py = entry.py.clone();
        ensure!(
            due.insert(py.clone(), entry).is_none(),
            "{PATH}: duplicate entry {py}"
        );
    }
    Ok(due)
}

pub(super) fn render(due: &PortDue) -> String {
    let mut document = DocumentMut::new();
    let mut rows = ArrayOfTables::new();
    for entry in due.values() {
        let mut table = Table::new();
        table["py"] = value(&entry.py);
        table["kind"] = value(&entry.kind);
        table["from"] = value(&entry.from);
        table["to"] = value(&entry.to);
        table["tag"] = value(&entry.tag);
        let mut symbols = Array::new();
        for name in &entry.symbols {
            symbols.push(name.as_str());
        }
        table["symbols"] = value(symbols);
        rows.push(table);
    }
    document["file"] = Item::ArrayOfTables(rows);
    format!("{HEADER}\n{document}")
}

/// Write the entries, removing the file when none remain.
pub(super) fn write(root: &Path, due: &PortDue) -> Result<()> {
    let path = root.join(PATH);
    if due.is_empty() {
        if path.try_exists()? {
            fs::remove_file(path)?;
        }
        return Ok(());
    }
    fs::write(path, render(due))?;
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    const A: &str = "1111111111111111111111111111111111111111";
    const B: &str = "2222222222222222222222222222222222222222";

    fn entry() -> Entry {
        Entry {
            py: "sdk/python/bittensor/example.py".into(),
            kind: "ported".into(),
            from: A.into(),
            to: B.into(),
            tag: "v487".into(),
            symbols: vec!["f".into()],
        }
    }

    #[test]
    fn entries_round_trip_and_an_empty_set_is_no_file() -> Result<()> {
        let due = PortDue::from([(entry().py.clone(), entry())]);
        assert_eq!(parse(&render(&due))?, due);
        assert!(parse(HEADER)?.is_empty());
        Ok(())
    }

    #[test]
    fn malformed_entries_are_refused() {
        for (key, bad) in [
            ("from", B),
            ("to", "pending"),
            ("kind", "other"),
            ("py", "../x"),
        ] {
            let mut text = render(&PortDue::from([(entry().py.clone(), entry())]));
            let line = text
                .lines()
                .find(|line| line.starts_with(&format!("{key} = ")))
                .map(str::to_owned)
                .unwrap_or_default();
            text = text.replace(&line, &format!("{key} = \"{bad}\""));
            assert!(parse(&text).is_err(), "{key} = {bad} accepted");
        }
    }
}
