//! Generate immutable named-network genesis inputs for the read client.

use std::{fs, path::Path};

use anyhow::{Context, Result, ensure};
use serde_json::{Value as Json, json};
use toml_edit::{DocumentMut, Item, Table, value};

const NETWORKS: &[(&str, &str, &str)] = &[
    ("finney", "finney", "FINNEY_GENESIS"),
    ("test", "testnet", "TEST_GENESIS"),
    ("devnet", "devnet", "DEVNET_GENESIS"),
];
const GENERATED: &str = "crates/rtao-client/src/generated/network_pins.rs";

fn genesis(input: &str) -> Result<&str> {
    ensure!(
        input.len() == 66
            && input.starts_with("0x")
            && input[2..]
                .bytes()
                .all(|byte| byte.is_ascii_hexdigit() && !byte.is_ascii_uppercase()),
        "genesis must be canonical lowercase 32-byte hex"
    );
    Ok(input)
}

fn endpoint(label: &str) -> Result<String> {
    let endpoint = rtao_catalog::py::NETWORKS
        .iter()
        .find(|(name, _)| *name == label)
        .map(|(_, endpoint)| endpoint.default)
        .with_context(|| format!("extracted network endpoint missing: {label}"))?;
    let authority = endpoint
        .strip_prefix("wss://")
        .context("named public network must use wss")?;
    Ok(format!("https://{authority}"))
}

fn collect(
    pins: &DocumentMut,
    rpc: &mut impl FnMut(&str, &str, Json) -> Result<Json>,
) -> Result<DocumentMut> {
    let mut next = pins.clone();
    for (label, section, _) in NETWORKS {
        let endpoint = endpoint(label)?;
        let first = rpc(&endpoint, "chain_getBlockHash", json!([0]))?;
        let first = genesis(
            first
                .as_str()
                .context("genesis RPC result must be a string")?,
        )?;
        let second = rpc(&endpoint, "chain_getBlockHash", json!([0]))?;
        ensure!(
            second.as_str() == Some(first),
            "{label} genesis changed between identity reads"
        );
        if let Some(previous) = pins
            .get("networks")
            .and_then(|networks| networks.get(section))
            .and_then(|network| network.get("genesis"))
        {
            ensure!(
                previous.as_str() == Some(first),
                "{label} genesis differs from the immutable recorded identity"
            );
        }
        if next["networks"].get(section).is_none() {
            next["networks"][section] = Item::Table(Table::new());
        }
        next["networks"][section]["genesis"] = value(first);
        next["networks"][section]["genesis_endpoint"] = value(&endpoint);
    }
    Ok(next)
}

fn render(pins: &DocumentMut) -> Result<String> {
    let mut output = String::from(
        "// @generated by cargo xtask pin --networks. Do not edit.\n\
         //! Named-network identities from upstream.toml.\n\n",
    );
    for (label, section, name) in NETWORKS {
        let hash = pins
            .get("networks")
            .and_then(|networks| networks.get(section))
            .and_then(|network| network.get("genesis"))
            .and_then(Item::as_str)
            .with_context(|| {
                format!("missing pinned {label} genesis; run cargo xtask pin --networks")
            })?;
        let hash = genesis(hash)?;
        output.push_str(&format!("/// Immutable genesis for the {label} network.\n"));
        let declaration = format!("pub const {name}: &str = {hash:?};");
        if declaration.len() > 100 {
            output.push_str(&format!("pub const {name}: &str =\n    {hash:?};\n\n"));
        } else {
            output.push_str(&format!("{declaration}\n\n"));
        }
    }
    output.pop();
    Ok(output)
}

/// Verify the derived client input against all three immutable pin records.
pub(super) fn verify(root: &Path, pins: &DocumentMut) -> Result<()> {
    let path = root.join(GENERATED);
    ensure!(
        fs::symlink_metadata(&path)?.file_type().is_file(),
        "generated genesis input must be a regular file"
    );
    ensure!(
        fs::read_to_string(&path)? == render(pins)?,
        "generated network identities differ from upstream.toml; run cargo xtask pin --networks"
    );
    Ok(())
}

/// Fetch consistent public genesis identities or verify their offline output.
pub(super) fn run(
    root: &Path,
    pins: &DocumentMut,
    check: bool,
    mut rpc: impl FnMut(&str, &str, Json) -> Result<Json>,
) -> Result<()> {
    if check {
        verify(root, pins)?;
        println!("Verified named-network genesis inputs offline");
        return Ok(());
    }
    let next = collect(pins, &mut rpc)?;
    let generated = root.join(GENERATED);
    fs::create_dir_all(generated.parent().context("network input has no parent")?)?;
    // Publish the derived file first, then the authoritative pin last. A failed
    // publication fails the offline check and a repeat recovers matching bytes.
    crate::pin::atomic_write(&generated, render(&next)?.as_bytes())?;
    crate::pin::atomic_write(&root.join("upstream.toml"), next.to_string().as_bytes())?;
    println!("Recorded immutable genesis inputs for finney, test and devnet");
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    fn hash(digit: char) -> String {
        format!("0x{}", digit.to_string().repeat(64))
    }

    fn pins() -> Result<DocumentMut> {
        format!(
            "[networks.finney]\ngenesis = {:?}\n[core]\ntag = \"v478\"\n",
            hash('1')
        )
        .parse()
        .map_err(Into::into)
    }

    #[test]
    fn generator_preserves_existing_pins_and_uses_extracted_endpoints() -> Result<()> {
        let mut seen = Vec::new();
        let generated = collect(&pins()?, &mut |endpoint, method, params| {
            ensure!(method == "chain_getBlockHash" && params == json!([0]));
            seen.push(endpoint.to_owned());
            Ok(json!(hash('1')))
        })?;
        ensure!(seen.len() == 6);
        for (index, (name, _, _)) in NETWORKS.iter().enumerate() {
            ensure!(seen[index * 2] == endpoint(name)?);
            ensure!(seen[index * 2 + 1] == endpoint(name)?);
        }
        ensure!(generated["core"]["tag"].as_str() == Some("v478"));
        ensure!(generated["networks"]["testnet"]["genesis"].as_str() == Some(hash('1').as_str()));
        ensure!(render(&generated)?.contains("pub const TEST_GENESIS"));
        Ok(())
    }

    #[test]
    fn recorded_identity_cannot_be_changed_or_overwritten() -> Result<()> {
        ensure!(collect(&pins()?, &mut |_, _, _| Ok(json!(hash('2')))).is_err());
        let mut calls = 0;
        ensure!(
            collect(&pins()?, &mut |_, _, _| {
                calls += 1;
                Ok(json!(hash(if calls == 1 { '1' } else { '2' })))
            })
            .is_err()
        );
        Ok(())
    }

    #[test]
    fn malformed_or_noncanonical_genesis_is_rejected() -> Result<()> {
        for bad in ["0x", "0x01", "0xgg", "", " 0x00"] {
            ensure!(genesis(bad).is_err());
        }
        ensure!(genesis(&hash('A')).is_err());
        ensure!(genesis(&hash('0')).is_ok());
        ensure!(collect(&pins()?, &mut |_, _, _| Ok(json!(null))).is_err());
        Ok(())
    }

    #[test]
    fn incomplete_named_inputs_cannot_generate_a_partial_signing_guard() -> Result<()> {
        ensure!(render(&pins()?).is_err());
        let generated = collect(&pins()?, &mut |_, _, _| Ok(json!(hash('1'))))?;
        let source = render(&generated)?;
        ensure!(source.matches("pub const ").count() == 3);
        ensure!(!source.contains("spec_version"));
        Ok(())
    }
}
